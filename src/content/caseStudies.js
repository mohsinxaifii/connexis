export const homeCases = [...caseStudies].sort((a, b) => a.homeOrder - b.homeOrder).slice(0, 6);

export function getCase(slug) {
  return caseStudies.find((c) => c.slug === slug);
}

export function caseNeighbours(slug) {
  const i = homeCases.findIndex((c) => c.slug === slug);
  const n = homeCases.length;
  return { prev: homeCases[(i - 1 + n) % n], next: homeCases[(i + 1) % n] };
}
